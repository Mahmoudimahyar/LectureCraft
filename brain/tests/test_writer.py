def _tree(root: Path) -> dict[str, str]:
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(root.rglob("*")) if p.is_file()}


@pytest.fixture()
def capture(settings):
    return CaptureStore(settings)


@pytest.fixture()
def facade(settings, capture):
    return WriterFacade(settings, capture)


def _frozen(capture, rid="req-1", text="Replication of the plasmid starts at the origin; it does not control expression.", family=Q1, question_id="BE505-L01-Q01", **kw):
    sub = submission(rid, text=text, prompt="Explain what the origin does.", question_id=question_id, family=family, **kw)
    return sub, capture.freeze_submission("be505", c.dump_json(sub))


def _candidate(sub, ref, attempt_id="be505-20261004-l01-q01-app-01", outcome="demonstrated", skills=("be505.skill.ori.explain",)):
    observations = [cand.observation(s, outcome, submission=sub, analysis="States that replication starts at the origin.") for s in skills]
    return cand.build_attempt_candidate(submission=sub, capture=ref, attempt_id=attempt_id, recorded_at=NOW, observations=observations)


# ---- happy path ----------------------------------------------------------------------------------
def test_attempt_is_saved_once_with_readback_and_separate_view_state(facade, capture, settings, be505):
    sub, ref = _frozen(capture)
    record = _candidate(sub, ref)
    receipt = facade.publish_attempt("be505", record, capture=ref, submission=sub, request_id="req-1", now="2026-10-04T10:00:31Z")
    assert receipt["status"] == "saved" and receipt["kind"] == "attempt" and receipt["writer_id"] == "coordinated-course-writer"
    dest = be505 / receipt["canonical_record"]["artifact"]["path"]
    data = dest.read_bytes()
    assert dest.parent.name == "2026-10" and dest.stem == record["attempt_id"]
    assert b"\r" not in data and not data.startswith(b"\xef\xbb\xbf") and data.endswith(b"\n")
    assert c.sha256_hex(data) == receipt["canonical_record"]["artifact"]["sha256"]
    assert receipt["captured_submission"] == ref
    # The owner's generated view was not regenerated by us: the attempt is saved, the view is stale.
    assert receipt["view_status"] == "stale"
    saved = json.loads(data)
    assert saved["time_basis"] == "recorded_now" and saved["occurred_at"] == saved["recorded_at"] == NOW
    assert saved["mode"] == "assess" and saved["observations"][0]["assistance"] == "none"
    assert ref["sha256"] in saved["response_evidence"]["locator"] and saved["response_evidence"]["excerpt"] in sub["response"]["text"]
    assert len(read_attempt_records(be505, "be505")["attempts"]) == 5


