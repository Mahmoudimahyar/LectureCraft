// Generates src/styles/tokens.css from the single design-token source
// (docs/project/design-tokens.json). `--check` fails when the committed CSS is stale.
//
// Emitted: the palette of each theme (every value an opaque #RRGGBB), the translucent washes
// (wash_pct, as color-mix over whatever ground is beneath), the two weights, the type scale per
// breakpoint in rem, the radii by role, the spacing steps and the motion durations.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../docs/project/design-tokens.json");
const out = resolve(here, "../src/styles/tokens.css");
const tokens = JSON.parse(readFileSync(source, "utf8"));

const kebab = (k) => k.replace(/_/g, "-");
const HEX = /^#[0-9a-fA-F]{6}$/;
// Sizes are emitted in rem so the learner's text-size setting (root font-size, lib/theme.ts) still scales them.
const rem = (px) => `${px / tokens.typography.base_px}rem`;

function palette(theme) {
  const lines = Object.entries(tokens[theme]).map(([k, v]) => {
    if (!HEX.test(v)) throw new Error(`${theme}.${k} must be an opaque #RRGGBB colour`);
    return `  --ll-${kebab(k)}: ${v};`;
  });
  // Washes stay translucent in CSS so one value works over every ground; the kit check composites them.
  const ink = `var(--ll-${kebab(tokens.wash_pct.ink)})`;
  for (const [name, pct] of Object.entries(tokens.wash_pct[theme])) {
    lines.push(`  --ll-${kebab(name)}: color-mix(in srgb, ${ink} ${pct}%, transparent);`);
  }
  return lines.join("\n");
}

function scaleAt(index) {
  const lines = [];
  for (const [role, row] of Object.entries(tokens.typography.scale_px)) {
    const first = index === 0;
    if (first || row.size[index] !== row.size[index - 1]) lines.push(`    --ll-fs-${kebab(role)}: ${rem(row.size[index])};`);
    if (first || row.line[index] !== row.line[index - 1]) lines.push(`    --ll-lh-${kebab(role)}: ${rem(row.line[index])};`);
  }
  return lines;
}
const steps = tokens.typography.scale_from_px;
for (const [role, row] of Object.entries(tokens.typography.scale_px)) {
  if (row.size.length !== steps.length || row.line.length !== steps.length) throw new Error(`typography.scale_px.${role} needs ${steps.length} values`);
}
const scaleBlocks = steps
  .map((from, index) => {
    const lines = scaleAt(index);
    if (!lines.length) return "";
    return index === 0 ? `:root {\n${lines.map((l) => l.slice(2)).join("\n")}\n}` : `@media (min-width: ${from}px) {\n  :root {\n${lines.join("\n")}\n  }\n}`;
  })
  .filter(Boolean)
  .join("\n\n");

const css = `/* GENERATED by scripts/gen-tokens.mjs from docs/project/design-tokens.json (v${tokens.version}) — do not edit. */
/* App UI only: original sources (slides, figures, media) are never recoloured or inverted. */
:root, [data-theme="light"] {
${palette("light")}
}

[data-theme="dark"] {
${palette("dark")}
}

:root {
  --ll-font-ui: ${tokens.typography.ui};
  --ll-line-height: ${tokens.typography.line_height};
${Object.entries(tokens.typography.weights).map(([k, v]) => `  --ll-weight-${kebab(k)}: ${v};`).join("\n")}
  --ll-radius: ${tokens.radius_px}px;
${Object.entries(tokens.radius_role_px).map(([k, v]) => `  --ll-radius-${kebab(k)}: ${v}px;`).join("\n")}
${tokens.spacing_px.map((v, i) => `  --ll-space-${i + 1}: ${v}px;`).join("\n")}
  --ll-motion-small: ${tokens.motion.small_ms}ms;
  --ll-motion-panel: ${tokens.motion.panel_ms}ms;
}

/* Type scale: one size and one line height per role, stepping at ${steps.slice(1).join(", ")} px. */
${scaleBlocks}

@media (prefers-reduced-motion: reduce) {
  :root {
    --ll-motion-small: ${tokens.motion.reduced_motion_ms}ms;
    --ll-motion-panel: ${tokens.motion.reduced_motion_ms}ms;
  }
}

[data-motion="reduced"] {
  --ll-motion-small: ${tokens.motion.reduced_motion_ms}ms;
  --ll-motion-panel: ${tokens.motion.reduced_motion_ms}ms;
}
`;

const normalize = (text) => String(text).split(String.fromCharCode(13)).join("");
if (process.argv.includes("--check")) {
  if (!existsSync(out) || normalize(readFileSync(out, "utf8")) !== normalize(css)) {
    console.error('Design token CSS is stale; run "npm run gen:tokens".');
    process.exit(1);
  }
  console.log("design tokens verified");
} else {
  writeFileSync(out, css);
  console.log("generated src/styles/tokens.css");
}
