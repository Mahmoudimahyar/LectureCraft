@pytest.mark.parametrize("case", ["missing_capture", "tampered_capture", "excerpt_not_in_capture", "wrong_turn"])
def test_unverifiable_sidecar_blocks_the_commit(facade, capture, settings, be505, case):
    sub, ref = _frozen(capture)
    record = _candidate(sub, ref)
    path = settings.write_root("be505") / ref["path"]
    claimed_sub = sub
    if case == "missing_capture":
        path.unlink()
    elif case == "tampered_capture":
        path.write_bytes(path.read_bytes().replace(b"origin", b"ORIGIN"))
    elif case == "excerpt_not_in_capture":
        record["response_evidence"]["excerpt"] = "A fluent answer the learner never gave."
    elif case == "wrong_turn":
        claimed_sub = dict(sub, turn_id="turn-other")
    before = _tree(be505 / "learning")
    receipt = facade.publish_attempt("be505", record, capture=ref, submission=claimed_sub, request_id="req-1", now="2026-10-04T10:00:31Z")
    assert receipt["status"] == "blocked" and receipt["canonical_record"] is None and "nothing was saved" in receipt["reason"]
    assert _tree(be505 / "learning") == before


@pytest.mark.parametrize("case", ["skill_set", "not_observed_with_error", "unknown_family", "template", "future_occurrence"])
def test_invalid_candidates_are_blocked_but_input_stays_captured(facade, capture, settings, be505, case):
    sub, ref = _frozen(capture)
    record = _candidate(sub, ref)
    if case == "skill_set":
        record["observations"].append(cand.observation("be505.skill.promoter.explain", "partial", submission=sub, analysis="x"))
    elif case == "not_observed_with_error":
        record["observations"][0].update(outcome="not_observed", error_types=["concept"])
    elif case == "unknown_family":
        record["question"]["family_id"] = "be505.family.does-not-exist"
    elif case == "template":
        record["TEMPLATE_ONLY"] = True
    elif case == "future_occurrence":
        record["occurred_at"] = "2026-10-05T00:00:00+00:00"
    before = _tree(be505 / "learning")
    receipt = facade.publish_attempt("be505", record, capture=ref, submission=sub, request_id="req-1", now="2026-10-04T10:00:31Z")
    assert receipt["status"] == "blocked" and receipt["canonical_record"] is None
    assert _tree(be505 / "learning") == before
    assert capture.verify("be505", ref)["response"]["text"] == sub["response"]["text"]  # the learner's input is still there


