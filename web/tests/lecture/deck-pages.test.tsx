// R2-S10 and the deck part of R2-T12 on screen: the Sources tab of a lecture states the pages of its deck by role, and
// the course readback under Settings states the deck of every lecture as a row of its own. Both show the raw page count
// and the teaching-content count together, the other roles in words so that everything adds up to the page count, and
// who set the roles. Rendered in jsdom with the synthetic sample; no percentage and nothing called complete.
import { describe, expect, it } from "vitest";
import { render, screen, within } from "@testing-library/react";
import { MemoryRouter } from "react-router";
import { SourcesPanel } from "@/features/lecture/SourcesPanel";
import { DeckReadbackRow } from "@/features/settings/SettingsPages";
import { sampleLectureView, sampleLectureViewWithoutR2 } from "@/lib/fixtures/r2-sample";
import { NBSP } from "@/lib/labels";
import type { DeckReadback, LectureView, SlideRoleValue } from "@/lib/types";

const plain = (value: string | null | undefined): string => (value ?? "").split(NBSP).join(" ").replace(/\s+/g, " ").trim();
const textOf = (element: Element | null): string => plain(element?.textContent);
const figure = (within_: HTMLElement, name: "raw" | "instructional"): string => textOf(within_.querySelector(`[data-figure="${name}"]`));
const numbers = (text: string): number[] => (text.match(/\d+/g) ?? []).map(Number);

describe("Sources tab: the pages of the deck by role", () => {
  const panel = (lecture: LectureView = sampleLectureView) => render(
    <MemoryRouter><SourcesPanel courseId="sample-course" lecture={lecture} page={4} slide={lecture.slides.find((slide) => slide.page === 4)} onPin={() => undefined} /></MemoryRouter>,
  );

  it("shows the raw page count and the teaching-content count as two labelled figures, in the list of the lecture's sources", () => {
    panel();
    const sources = screen.getByRole("region", { name: "Sources of this lecture" });
    const pages = within(sources).getByTestId("deck-pages");
    expect(figure(pages, "raw")).toBe("PDF pages 12");
    expect(figure(pages, "instructional")).toBe("Count as teaching content 8");
    // The row of the file itself is as it was.
    expect(textOf(within(sources).getByTestId("source-deck"))).toBe("12 pages. sample-deck-90.pdf · version v1-dddddddddddd");
  });

  it("counts the other roles in words, and what is on screen adds up to the page count", () => {
    panel();
    const pages = screen.getByTestId("deck-pages");
    const others = textOf(within(pages).getByTestId("deck-other-roles"));
    expect(others).toBe("2 pages are listed as uncertain, not excluded: 1 objectives or summary page, 1 page of unknown role. 2 pages are excluded: 1 title or section page, 1 administrative page.");
    const [uncertain, excluded] = others.split(". ").filter((part) => /^\d+ pages? (is|are) (listed|excluded)/.test(part)).map((part) => numbers(part)[0]!);
    expect(numbers(figure(pages, "instructional"))[0]! + uncertain! + excluded!).toBe(numbers(figure(pages, "raw"))[0]);
  });

  it("says who set the roles, deck-wide and for the pages outside the teaching count", () => {
    panel();
    expect(textOf(screen.getByTestId("deck-roles-established"))).toBe("Roles: 10 generated by the detector, 1 set by you, 1 set by an agent. Of the 4 pages outside the teaching count: 1 set by you, 3 generated by the detector.");
  });

  it("uses no percentage and calls nothing complete", () => {
    panel();
    expect(textOf(screen.getByTestId("deck-pages"))).not.toMatch(/%|percent|complete|done|finished|covered/i);
  });

  it("states only the page count, with the cause, when the deck has no source map", () => {
    // A Brain that states no source map at all: nothing is said about roles.
    const older = panel(sampleLectureViewWithoutR2);
    expect(screen.queryByTestId("deck-pages")).toBeNull();
    older.unmount();
    const unmapped: LectureView = { ...sampleLectureView, source_map: { state: "unavailable", reason: "not_built", denominators: { raw: 12, instructional: null, by_role: null, uncertain: null, excluded: null }, limitations: [] },
      slides: sampleLectureView.slides.map((slide) => ({ ...slide, role: { value: "unknown" as SlideRoleValue, state: null, uncertain: true, forced_requirements: true, basis: [] } })) };
    panel(unmapped);
    const stated = screen.getByTestId("deck-pages");
    expect(figure(stated, "raw")).toBe("PDF pages 12");
    expect(stated.querySelector('[data-figure="instructional"]')).toBeNull();
    expect(textOf(stated)).toContain("The roles of these pages are not established, so no teaching-content count is stated: the source map has not been built yet.");
    expect(within(stated).queryByTestId("deck-other-roles")).toBeNull();
  });
});

describe("Settings, Build and data: the deck of a lecture in the course readback", () => {
  const stored: DeckReadback = {
    source_id: "src-sample-deck-90", filename: "sample-deck-90.pdf", state: "pdf", page_count: 14, map_state: "stored", cause: null,
    denominators: { raw: 14, instructional: 10, uncertain: 2, excluded: 2,
      by_role: { instructional: 9, worked_example_or_question: 1, mixed: 0, objectives_or_summary: 2, unknown: 0, structural_title_or_section: 1, administrative: 1, blank: 0 } },
    roles_established: { generated: 14, agent_reviewed: 0, human_confirmed: 0 }, roles_established_outside: { generated: 4, agent_reviewed: 0, human_confirmed: 0 },
  };
  const none = { page_count: null, map_state: null, denominators: null, roles_established: null, roles_established_outside: null } as const;
  const row = (deck: DeckReadback | null | undefined, summary?: { pages: number | null; pages_with_range: number | null } | null) => render(<DeckReadbackRow deck={deck} summary={summary} />);

  it("names the file and its state, then both figures, the other roles, who set the roles and on how many pages a range lies", () => {
    row(stored, { pages: 14, pages_with_range: 8 });
    const deck = screen.getByTestId("deck-row");
    expect(deck).toHaveAttribute("data-deck-state", "pdf");
    expect(figure(deck, "raw")).toBe("14 PDF pages");
    expect(figure(deck, "instructional")).toBe("10 count as teaching content");
    expect(textOf(deck)).toBe("Slides: sample-deck-90.pdf. Readable PDF. 14 PDF pages, 10 count as teaching content. 2 objectives or summary pages are listed as uncertain, not excluded. "
      + "2 pages are excluded: 1 title or section page, 1 administrative page. Roles: 14 generated by the detector, none set by you or by an agent. Ranges on 8 of 14 pages.");
    expect(textOf(deck)).not.toMatch(/%|complete|done|finished/i);
  });

  it("says who set aside the pages that were re-labelled", () => {
    row({ ...stored, denominators: { raw: 14, instructional: 10, uncertain: 0, excluded: 4,
      by_role: { instructional: 9, worked_example_or_question: 1, mixed: 0, objectives_or_summary: 0, unknown: 0, structural_title_or_section: 1, administrative: 2, blank: 1 } },
      roles_established: { generated: 12, agent_reviewed: 0, human_confirmed: 2 }, roles_established_outside: { generated: 2, agent_reviewed: 0, human_confirmed: 2 } });
    const deck = screen.getByTestId("deck-row");
    expect(figure(deck, "raw")).toBe("14 PDF pages");
    expect(textOf(deck)).toContain("4 pages are excluded: 1 title or section page, 2 administrative pages, 1 blank page. Roles: 12 generated by the detector, 2 set by you. "
      + "Of the 4 pages outside the teaching count: 2 set by you, 2 generated by the detector.");
    expect(textOf(deck)).not.toContain("Ranges on"); // no figure was sent for ranges: nothing is said
  });

  it("states the cause in words where no page is counted, and no figure", () => {
    const cases: Array<[DeckReadback, string]> = [
      [{ ...stored, ...none, map_state: "not_built", cause: "not_built" }, "Slides: sample-deck-90.pdf. Readable PDF. Its pages are not counted yet: the source map of this file has not been built."],
      [{ ...stored, ...none, filename: "Sample 92.pptx", state: "not_a_pdf", cause: "not_a_pdf" }, "Slides: Sample 92.pptx. PowerPoint only: no pages. Pages are counted in a PDF file only."],
      [{ ...stored, ...none, filename: "Sample empty.pdf", state: "unreadable", cause: "unreadable" }, "Slides: Sample empty.pdf. Unreadable. The file is missing, empty or could not be read, so no pages are counted."],
      [{ ...stored, ...none, source_id: null, filename: null, state: "no_deck", cause: "no_deck" }, "Slides: No deck named. No slides file is chosen for this lecture, so no pages are counted."],
    ];
    for (const [deck, words] of cases) {
      const view = row(deck, { pages: null, pages_with_range: null });
      const shown = screen.getByTestId("deck-row");
      expect(textOf(shown)).toBe(words);
      expect(shown).toHaveAttribute("data-deck-state", deck.state);
      expect(shown.querySelector("[data-figure]")).toBeNull();
      view.unmount();
    }
  });

  it("draws nothing for a Brain that states no deck", () => {
    const { container } = row(undefined);
    expect(container).toBeEmptyDOMElement();
  });
});
