// Generates browser contract artifacts from the single local schema set (contracts/v1):
//   src/contracts/generated/types.d.ts     TypeScript types (json-schema-to-typescript)
//   src/contracts/generated/validators.js  Precompiled Ajv 2020 standalone validators (no eval → strict CSP)
//   src/contracts/generated/meta.ts        Digest of the schema set the artifacts were generated from
// No schema is ever fetched from the network: $refs are resolved against local files only.
import { readFileSync, writeFileSync as writeFileSyncReal, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = resolve(here, "../../contracts");
const out = resolve(here, "../src/contracts/generated");
mkdirSync(out, { recursive: true });
const checkOnly = process.argv.includes("--check");
const stale = [];
const normalize = (text) => String(text).split(String.fromCharCode(13)).join("");
const writeFileSync = (file, content) => {
  if (!checkOnly) return writeFileSyncReal(file, content);
  const current = existsSync(file) ? normalize(readFileSync(file, "utf8")) : null;
  if (current !== normalize(content)) stale.push(file);
};

const index = JSON.parse(readFileSync(resolve(contracts, "index.json"), "utf8"));
const names = [...index.schemas.map((s) => s.name), "common"].sort();
const raw = Object.fromEntries(names.map((n) => [n, readFileSync(resolve(contracts, `v1/${n}.schema.json`))]));
const schemas = Object.fromEntries(names.map((n) => [n, JSON.parse(raw[n].toString("utf8"))]));

const digest = createHash("sha256");
for (const n of names) digest.update(raw[n]);
digest.update(readFileSync(resolve(contracts, "index.json")));
const schemaSetSha = digest.digest("hex");

// --- validators ---
const ajv = new Ajv2020({ strict: true, allErrors: false, code: { source: true, esm: true } });
addFormats(ajv, ["date-time"]);
for (const n of names) ajv.addSchema(schemas[n]);
const exportsMap = Object.fromEntries(names.filter((n) => n !== "common").map((n) => [n.replace(/-/g, "_"), schemas[n].$id]));
let code = standaloneCode(ajv, exportsMap);
// ajv emits CommonJS require() calls for its runtime helpers even in ESM mode. Route them through one
// local shim so CJS/ESM interop differences between Node, Vite and Vitest cannot change behaviour.
const known = {
  'require("ajv/dist/runtime/ucs2length").default': "__rt.ucs2length",
  'require("ajv-formats/dist/formats").fullFormats': "__rt.fullFormats",
};
for (const [from, to] of Object.entries(known)) code = code.split(from).join(to);
if (/require\(/.test(code)) throw new Error("Unhandled require() in generated validators");
writeFileSync(resolve(out, "validators.js"), `// GENERATED by scripts/gen-types.mjs — do not edit.\n/* eslint-disable */\nimport * as __rt from "../ajv-runtime";\n${code}\n`);
writeFileSync(
  resolve(out, "validators.d.ts"),
  `// GENERATED by scripts/gen-types.mjs — do not edit.\ninterface ValidateFn { (data: unknown): boolean; errors?: Array<{ instancePath: string; message?: string; keyword: string }> | null }\n` +
    Object.keys(exportsMap).map((k) => `export declare const ${k}: ValidateFn;`).join("\n") + "\n",
);

// --- types ---
const commonDefs = schemas.common.$defs;
const deref = (node) => {
  if (Array.isArray(node)) return node.map(deref);
  if (node && typeof node === "object") {
    if (typeof node.$ref === "string") {
      const m = node.$ref.match(/common\.schema\.json#\/\$defs\/([A-Za-z_]+)$/);
      if (!m || !commonDefs[m[1]]) throw new Error(`Unresolvable local $ref: ${node.$ref}`);
      return deref(commonDefs[m[1]]);
    }
    return Object.fromEntries(Object.entries(node).filter(([k]) => k !== "$id" && k !== "$schema").map(([k, v]) => [k, deref(v)]));
  }
  return node;
};
const pascal = (n) => n.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
let types = `// GENERATED by scripts/gen-types.mjs from contracts/v1 — do not edit.\n// Schema set sha256: ${schemaSetSha}\n\n`;
for (const n of names.filter((x) => x !== "common")) {
  const flat = deref(schemas[n]);
  flat.title = `${pascal(n)}Record`;
  types += await compile(flat, `${pascal(n)}Record`, { bannerComment: "", additionalProperties: false, format: false, declareExternallyReferenced: true });
  types += "\n";
}
for (const d of ["source", "artifact", "scope", "question", "evidence_ref"]) {
  const flat = deref(commonDefs[d]);
  const name = `Common${pascal(d.replace(/_/g, "-"))}`;
  flat.title = name;
  types += await compile(flat, name, { bannerComment: "", additionalProperties: false, format: false });
  types += "\n";
}
writeFileSync(resolve(out, "types.d.ts"), types);
writeFileSync(
  resolve(out, "meta.ts"),
  `// GENERATED by scripts/gen-types.mjs — do not edit.\nexport const SCHEMA_SET_SHA256 = "${schemaSetSha}";\nexport const ACTION_PAYLOADS = ${JSON.stringify(index.action_payloads, null, 2)} as const;\nexport const SCHEMA_NAMES = ${JSON.stringify(names.filter((n) => n !== "common"))} as const;\n`,
);
if (checkOnly && stale.length) {
  console.error('Generated contract artifacts are stale; run "npm run gen:types": ' + stale.join(", "));
  process.exit(1);
}
console.log(`${checkOnly ? "verified" : "generated"} ${names.length - 1} validators/types; schema set ${schemaSetSha.slice(0, 12)}`);
