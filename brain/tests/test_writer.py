def test_revision_chain_is_nonbranching_and_keeps_the_same_skills(facade, capture, be505):
    sub, ref = _frozen(capture)
    attempt = "be505-20260905-l01-q01-teachback-01"
    ok = facade.publish_revision("be505", _revision("be505-20261004-regrade-a", attempt), capture=ref, submission=sub, request_id="req-r1", now="2026-10-04T10:01:00Z")
    assert ok["status"] == "saved" and ok["kind"] == "assessment_revision"
    records = read_attempt_records(be505, "be505")
    assert len(records["attempts"]) == 4 and records["effective"][attempt]["assessment_id"] == "be505-20261004-regrade-a"  # no new learner attempt
    branch = facade.publish_revision("be505", _revision("be505-20261004-regrade-b", attempt), capture=ref, submission=sub, request_id="req-r2", now="2026-10-04T10:02:00Z")
    assert branch["status"] == "blocked" and "branch" in branch["reason"]
    widened = facade.publish_revision("be505", _revision("be505-20261004-regrade-c", "be505-20261004-regrade-a", skills=("be505.skill.ori.explain", "be505.skill.promoter.explain")),
                                      capture=ref, submission=sub, request_id="req-r3", now="2026-10-04T10:03:00Z")
    assert widened["status"] == "blocked" and "skill set" in widened["reason"]
    assert read_attempt_records(be505, "be505")["problems"] == []
    original = json.loads((be505 / "learning/attempts/2026-09" / f"{attempt}.json").read_text(encoding="utf-8"))
    assert original["observations"][0]["outcome"] == "partial"  # original evidence untouched


