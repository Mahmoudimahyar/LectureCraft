def test_identical_retry_is_a_noop_and_different_bytes_conflict(facade, capture, be505):
    sub, ref = _frozen(capture)
    record = _candidate(sub, ref)
    first = facade.publish_attempt("be505", record, capture=ref, submission=sub, request_id="req-1", now="2026-10-04T10:00:31Z")
    again = facade.publish_attempt("be505", record, capture=ref, submission=sub, request_id="req-1", now="2026-10-04T10:00:40Z")
    assert again["status"] == "already_saved" and again["canonical_record"] == first["canonical_record"]
    before = (be505 / first["canonical_record"]["artifact"]["path"]).read_bytes()
    changed = _candidate(sub, ref, outcome="partial")
    conflict = facade.publish_attempt("be505", changed, capture=ref, submission=sub, request_id="req-1", now="2026-10-04T10:00:50Z")
    assert conflict["status"] == "blocked" and conflict["canonical_record"] is None and "different bytes" in conflict["reason"]
    assert (be505 / first["canonical_record"]["artifact"]["path"]).read_bytes() == before
    assert len(read_attempt_records(be505, "be505")["attempts"]) == 5  # one accepted learner attempt


